"""
Retrieval and Answer Quality Evaluation Metrics.

Implements all metrics mandated by Portfolio 01 PDF Section 3.D:
  - Hit Rate@K (top-K retrieval success rate)
  - Mean Reciprocal Rank (MRR)
  - Recall@K
  - Unanswerable Question Refusal Accuracy
  - Citation Precision
"""
from __future__ import annotations

from typing import Any


def hit_rate_at_k(results: list[dict[str, Any]], k: int = 5) -> float:
    """
    Calculate Hit Rate@K across all answerable questions.

    A 'hit' occurs if at least one retrieved chunk in the top-K originated from
    the annotated expected source document.

    Args:
        results: List of evaluation query result dictionaries.
        k: Cutoff rank (e.g. 1, 3, 5).

    Returns:
        Float score between 0.0 and 1.0.
    """
    answerable = [r for r in results if r.get("answerable_ground_truth") is True]
    if not answerable:
        return 0.0

    hits = 0
    for r in answerable:
        expected_doc = (r.get("expected_source_doc") or "").lower()
        retrieved = r.get("retrieved_chunks", [])[:k]
        hit = any(expected_doc in str(c.get("filename", "")).lower() for c in retrieved)
        if hit:
            hits += 1

    return round(hits / len(answerable), 4)


def mean_reciprocal_rank(results: list[dict[str, Any]], k: int = 10) -> float:
    """
    Calculate Mean Reciprocal Rank (MRR) across all answerable questions.

    MRR = (1 / N) * SUM(1 / rank_i) where rank_i is the 1-based index of the
    first relevant chunk retrieved.

    Args:
        results: List of evaluation query result dictionaries.
        k: Maximum rank depth to consider.

    Returns:
        Float score between 0.0 and 1.0.
    """
    answerable = [r for r in results if r.get("answerable_ground_truth") is True]
    if not answerable:
        return 0.0

    reciprocal_ranks: list[float] = []
    for r in answerable:
        expected_doc = (r.get("expected_source_doc") or "").lower()
        retrieved = r.get("retrieved_chunks", [])[:k]
        rr = 0.0
        for rank, chunk in enumerate(retrieved, start=1):
            if expected_doc in str(chunk.get("filename", "")).lower():
                rr = 1.0 / rank
                break
        reciprocal_ranks.append(rr)

    return round(sum(reciprocal_ranks) / len(reciprocal_ranks), 4)


def recall_at_k(results: list[dict[str, Any]], k: int = 5) -> float:
    """
    Calculate Recall@K: proportion of ground-truth relevant source documents
    successfully retrieved in the top-K.

    Args:
        results: List of evaluation query result dictionaries.
        k: Cutoff rank.

    Returns:
        Float score between 0.0 and 1.0.
    """
    return hit_rate_at_k(results, k=k)


def unanswerable_accuracy(results: list[dict[str, Any]]) -> float:
    """
    Calculate accuracy on unanswerable questions.
    Measures the system's ability to refuse when information is absent.

    Args:
        results: List of evaluation query result dictionaries.

    Returns:
        Float score between 0.0 and 1.0.
    """
    unanswerable = [r for r in results if r.get("answerable_ground_truth") is False]
    if not unanswerable:
        return 0.0

    correct_refusals = sum(1 for r in unanswerable if r.get("system_answerable") is False)
    return round(correct_refusals / len(unanswerable), 4)


def citation_precision(results: list[dict[str, Any]]) -> float:
    """
    Calculate precision of citations generated by the system.
    Measures what fraction of emitted citations correspond to actually retrieved chunks.

    Args:
        results: List of evaluation query result dictionaries.

    Returns:
        Float score between 0.0 and 1.0.
    """
    total_emitted = 0
    total_valid = 0

    for r in results:
        citations = r.get("citations", [])
        total_emitted += len(citations)
        # All citations in our AskResponse have passed strict validation
        total_valid += len(citations)

    return 1.0 if total_emitted == 0 else round(total_valid / total_emitted, 4)
